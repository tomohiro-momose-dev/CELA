"""
BL-306: BL-278（複数候補からの選定妥当性・十分性チェック）が、選定基準の「有無」だけを
確認し、その基準が実質的に十分性を説明しているかを評価していなかった問題の修正。

ユーザー指摘の発端: run_id=1787890406-1e73a89dのtask_1_2成果物で、ゴール文が「小学校、
中学校、高校」と明示的に3種の学校を列挙しているにもかかわらず、成果物は「学校群」を
永明小学校1校（GIS代表地点）で代表させ、かつ通学需要の計上は別の茅野高校を対象とする
という、代表地点と需要対象が食い違ったまま中学校を完全に欠落させていた。

実際のDetector審査記録（agreements.reason_why、topic="task_1_2_domain_validity_review"）
を確認したところ、BL-278チェックの結果は次の一文のみだった:
「複数候補からの選定(BL-278)は代表地点の選択に基準(代表地点)が明記され問題なし。」

BL-278のプロンプト指示は本来「選定基準が明記されている場合：その基準が...本質に照らして
量・範囲として十分か評価してください」と、基準の**十分性**を問うものだったが、実際の判定は
「代表地点」というラベルの**存在**を確認しただけで停止しており、なぜ1点の代表化でゴール文が
列挙する複数種別を十分にカバーできるかという実質的な理由は一切問われていなかった。

ユーザー指示（原文）: 「プロンプトは具体的に、一般的に書いてください」——学校固有の
特殊対応ではなく、同種の問題（ゴール文が複数のサブカテゴリを明示的に列挙しているのに、
成果物が1つの代表項目だけで束ねて他を無言で切り捨てるパターン）全般に適用できる、
一般化された形でプロンプトを強化する。

対応: BL-278ブロックに、「基準が明記されている」とみなせる条件を明確化する一文を追加。
役割ラベル（「代表値として」「代表地点として」等）を添えただけで十分性の理由が伴っていない
ものは、基準明記なしと同様に扱う（＝minor以上の根拠にできる）よう指示した。特に、ゴール文・
指示・本質記述の側が対象を複数の名称付きサブカテゴリとして明示的に列挙しているのに、
成果物が一部だけを代表として扱っている場合を重点確認対象として明示した。

参照: BL-278（原設計）、BL-279（reason_why要約の全文確認指示、隣接ブロック）。
実LLM API呼び出しは伴わない（プロンプト文言の存在・位置関係の確認のみ）。
"""

import inspect

import cela_main


def _domain_prompt_source_block():
    """call_detector関数のソースから、BL-278ブロックを含む領域の文字列を取得する。
    domain_promptはf-string結合のPython関数呼び出し内で組み立てられるため、実際の
    プロンプト文字列そのものではなくソースコード中の文字列リテラルを対象に検証する
    （BL-301のテストと同型のアプローチ）。"""
    return inspect.getsource(cela_main.call_detector)


def test_bl306_label_only_criterion_is_explicitly_rejected():
    """[BL-306本体] 「基準が明記されている」とみなす条件として、役割ラベルの提示だけでは
    不十分であり、実質的な十分性の理由が必要である旨がプロンプトに明記されていること。"""
    src = _domain_prompt_source_block()
    assert "役割ラベルを添えただけ" in src
    assert "理由が伴っていない" in src
    assert "明記されていないのと同様に扱ってください" in src


def test_bl306_is_generalized_not_school_specific():
    """[一般化の確認] ユーザー指示「プロンプトは具体的に、一般的に書いてください」に従い、
    「学校」「小学校」「中学校」「高校」等の固有名詞をプロンプトへ直接埋め込んでいない
    （学校ケース専用のパッチになっていない）こと。一方で、同種のパターン（ゴール文が
    複数の名称付きサブカテゴリを列挙しているのに一部だけを代表として扱う）を一般的な
    言葉で明示していること。"""
    src = _domain_prompt_source_block()
    bl306_start = src.index("[BL-306]")
    bl306_end = src.index("[BL-279]", bl306_start)
    bl306_block = src[bl306_start:bl306_end]
    for word in ("小学校", "中学校", "高校", "茅野"):
        assert word not in bl306_block, f"BL-306ブロックに固有名詞が残っている: {word}"
    assert "複数の名称付きサブカテゴリ" in bl306_block


def test_bl306_positioned_within_bl278_block_before_bl279():
    """[配線確認] BL-306の追記が、BL-278ブロック内・BL-279ブロックより前という
    意図した位置に挿入されていること（本質チェックの直後に「基準十分性」を問う
    元の設計順序を崩していない）。"""
    src = _domain_prompt_source_block()
    idx_278 = src.index("[BL-278: 複数候補からの選定妥当性・十分性チェック]")
    idx_306 = src.index("[BL-306]")
    idx_279 = src.index("[BL-279] 決定事項DBに表示されている")
    assert idx_278 < idx_306 < idx_279


def test_bl306_original_sufficiency_instruction_still_present():
    """[非退行] BL-278の元々の「基準が本質に照らして量・範囲として十分か評価」という
    指示文自体は変更・削除されていないこと。"""
    src = _domain_prompt_source_block()
    # [BL-312] キャッシュ効率化のためプロンプトを静的先頭・動的末尾へ再構成した際、
    # 「上記【🎯 本質】」という位置参照を「後述の【🎯 本質】」という自己完結文へ書き換えた
    # （意味は不変、参照方向が反転しただけ）。
    assert "その基準が後述の【🎯 本質】（受益者ニーズ）に照らして" in src
    assert "量・範囲として" in src
